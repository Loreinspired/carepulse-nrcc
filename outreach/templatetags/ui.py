@register.simple_tag
def icon(name: str, css_class: str = "icon", label: str = ""):
    """Render an inline SVG icon. Decorative unless a label is given."""
    paths = _ICONS.get(name)
    if paths is None:
        return ""
    aria = format_html('role="img" aria-label="{}"', label) if label else mark_safe('aria-hidden="true"')
    return format_html(
        '<svg class="{}" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" focusable="false" {}>{}</svg>',
        css_class,
        aria,
        mark_safe(paths),
    )


@register.filter
def phone_display(phone_e164: str) -> str:
    """+2348031234567 -> 0803 123 4567 (how Nigerians write numbers); other numbers unchanged."""
    if phone_e164 and phone_e164.startswith("+234") and len(phone_e164) == 14:
        national = "0" + phone_e164[4:]
        return f"{national[:4]} {national[4:7]} {national[7:]}"
    return phone_e164 or ""


@register.filter
def initials(contact) -> str:
    first = (getattr(contact, "first_name", "") or "").strip()[:1]
    last = (getattr(contact, "last_name", "") or "").strip()[:1]
    return (first + last).upper() or "?"


